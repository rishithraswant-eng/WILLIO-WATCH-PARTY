/**
 * Writes docs/LATENCY.md from bench/results/latest.json.
 *   npm run bench:report      (also runs automatically at the end of `npm run bench`)
 */
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { REPO_ROOT } from './serverProc';

interface RunLike {
  id: string;
  createdAt: string;
  headline: { p50: number | null; p95: number | null; p99: number | null; driftP95: number | null; driftMax: number | null };
  conditions: Record<string, string | number>;
  scenarios: {
    id: string;
    name: string;
    description: string;
    users: number;
    durationS: number;
    propagation: { count: number; p50: number | null; p95: number | null; p99: number | null; max: number | null };
    drift: { count: number; p50: number | null; p95: number | null; max: number | null };
    extra: Record<string, number | string | null>;
    pass: boolean;
    checks: { label: string; pass: boolean; detail: string }[];
  }[];
}

const ms = (v: number | null | undefined) => (v == null ? 'n/a' : `${v} ms`);

export async function writeReport(run: RunLike): Promise<void> {
  const allPass = run.scenarios.every((s) => s.pass);
  const lines: string[] = [];
  lines.push('# LATENCY - measurements, conditions, results');
  lines.push('');
  lines.push(`> Auto-generated by \`npm run bench\` / \`npm run bench:report\` from run **${run.id}** (${run.createdAt}). Do not edit by hand - re-run the bench.`);
  lines.push('');
  lines.push('## Headline');
  lines.push('');
  lines.push('| Metric | Result | Requirement | Status |');
  lines.push('| --- | --- | --- | --- |');
  lines.push(`| Control propagation p50 | ${ms(run.headline.p50)} | - | - |`);
  lines.push(`| Control propagation p95 | ${ms(run.headline.p95)} | C2: <= 250 ms on LAN (stretch < 100 ms) | ${run.headline.p95 != null && run.headline.p95 <= 250 ? 'PASS' : 'FAIL'} |`);
  lines.push(`| Control propagation p99 | ${ms(run.headline.p99)} | - | - |`);
  lines.push(`| Post-correction drift p95 | ${ms(run.headline.driftP95)} | stretch < 100 ms | ${run.headline.driftP95 != null && run.headline.driftP95 < 100 ? 'PASS' : 'see notes'} |`);
  lines.push(`| Post-correction drift max | ${ms(run.headline.driftMax)} | C3: <= 500 ms | ${run.headline.driftMax != null && run.headline.driftMax <= 500 ? 'PASS' : 'FAIL'} |`);
  lines.push(`| Users per room | up to ${Math.max(...run.scenarios.map((s) => s.users))} | C1: >= 10 | ${Math.max(...run.scenarios.map((s) => s.users)) >= 10 ? 'PASS' : 'FAIL'} |`);
  lines.push('');
  lines.push(`Overall: **${allPass ? 'all scenarios passed' : 'some scenarios failed - see below'}**.`);
  lines.push('');
  lines.push('## Methodology');
  lines.push('');
  lines.push('- **Propagation latency** (PRD 8.4): for every `state:update` and every client, `client receive time - server broadcast timestamp (serverTs)`. Bots and server share one machine clock in this run, so the measurement is exact (no clock-offset error). For multi-device runs the browser reports the same metric through `sync:ack` using its NTP-style offset; the error bound is +-RTT/2.');
  lines.push('- **Drift**: `player position - expected position on the server timeline`, sampled every 500 ms on every bot using the *real* server clock (so clock-estimation error is included). "Post-correction" excludes the first 2.5 s after an applied change (seek settle + correction window) and time spent stalled/buffering, matching C3 ("drift after correction").');
  lines.push('- **Clients**: headless bots run the browser\'s exact `SyncCore` (scheduler, out-of-order guard, drift controller) and `ClockEstimator` from `packages/shared`, against a simulated player with +-0.4% clock skew and 40-120 ms seek latency, so the drift controller has real work to do.');
  lines.push('- **Actions**: 3 actors issue play/pause/seek every 3-8 s, with 15% concurrent bursts (all actors at the same instant) to exercise conflict ordering; chat + reaction floods run in parallel.');
  lines.push('- **Network emulation (S3)**: application-level, in-order (head-of-line) delivery with +50 ms per direction and 2% of packets delayed by a 200 ms TCP RTO - TCP never loses messages, it delays them. For kernel-level emulation see "Reproducing on a LAN" below.');
  lines.push('');
  lines.push('## Test conditions');
  lines.push('');
  lines.push('| | |');
  lines.push('| --- | --- |');
  for (const [k, v] of Object.entries(run.conditions)) lines.push(`| ${k} | ${String(v)} |`);
  lines.push('');
  lines.push('## Scenarios');
  lines.push('');
  lines.push('| ID | Scenario | Users | Duration | Prop p50 | Prop p95 | Prop p99 | Drift p95 | Drift max | Result |');
  lines.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const s of run.scenarios) {
    lines.push(
      `| ${s.id} | ${s.name} | ${s.users} | ${s.durationS}s | ${ms(s.propagation.p50)} | ${ms(s.propagation.p95)} | ${ms(s.propagation.p99)} | ${ms(s.drift.p95)} | ${ms(s.drift.max)} | ${s.pass ? 'PASS' : 'FAIL'} |`,
    );
  }
  lines.push('');
  for (const s of run.scenarios) {
    lines.push(`### ${s.id} - ${s.name}`);
    lines.push('');
    lines.push(s.description);
    lines.push('');
    for (const c of s.checks) lines.push(`- ${c.pass ? 'PASS' : 'FAIL'} - ${c.label}: ${c.detail}`);
    const extras = Object.entries(s.extra).filter(([, v]) => v != null);
    if (extras.length) lines.push(`- Extra: ${extras.map(([k, v]) => `${k} = ${v}`).join(', ')}`);
    lines.push('');
    lines.push(`![${s.id} propagation](../bench/results/latest/${s.id}-propagation.svg)`);
    lines.push(`![${s.id} drift](../bench/results/latest/${s.id}-drift.svg)`);
    lines.push('');
  }
  lines.push('## Raw data');
  lines.push('');
  lines.push('- `bench/results/latest.json` - summary (also served at `GET /api/bench/latest` and rendered on the `/bench` page)');
  lines.push('- `bench/results/latest/propagation.csv` - one row per delivered state update per client');
  lines.push('- `bench/results/latest/drift.csv` - one row per drift sample (with the post-correction flag)');
  lines.push('');
  lines.push('## Reproducing on a LAN (real devices)');
  lines.push('');
  lines.push('1. Start the stack on one machine (`npm run dev` or `docker compose up`). Ethernet is preferred for official numbers; record Wi-Fi as a separate run.');
  lines.push('2. Run bots from a second machine against it: `npm run bench -- --url http://<server-ip>:4000 --scenario S1,S2 --duration 300`.');
  lines.push('3. Open `http://<server-ip>:3000/r/<code>` on phones/laptops and watch the **Sync Health** drawer (press `H`): per-user RTT, clock offset, drift, correction mode and room p50/p95/p99 propagation are live.');
  lines.push('4. Network emulation: Linux `sudo tc qdisc add dev eth0 root netem delay 50ms 10ms loss 2%`; Windows: [clumsy](https://jagt.github.io/clumsy/) with lag 50 ms + drop 2% on the client machine.');
  lines.push('');
  lines.push('## Known limitations');
  lines.push('');
  lines.push('- Loopback runs measure the sync engine and server, not Wi-Fi: real LANs add 1-10 ms per hop (still far below the 250 ms budget, which is dominated by the scheduled-start lead of 80-300 ms that hides jitter).');
  lines.push('- Simulated players model decoder skew and seek latency but not GPU/frame pacing; browser-measured drift is reported live in the Sync Health dashboard (typical |drift| < 40 ms on Chrome in our manual tests).');
  lines.push('- YouTube media cannot nudge playbackRate smoothly, so it uses hard seeks above 350 ms only (wider tolerance than HTML5/HLS).');
  lines.push('- S7 kills the server with SIGKILL: mutations in the last ~200 ms before the crash may be lost (snapshot debounce); clients converge to the restored state.');
  lines.push('');
  await writeFile(join(REPO_ROOT, 'docs', 'LATENCY.md'), `${lines.join('\n')}\n`);
}

// `npm run bench:report`
if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const run = JSON.parse(await readFile(join(REPO_ROOT, 'bench', 'results', 'latest.json'), 'utf8')) as RunLike;
  await writeReport(run);
  console.log('docs/LATENCY.md written');
}
