export type IconName = keyof typeof ICONS;

function runs(rows: readonly string[]): { x: number; y: number; w: number }[] {
  const out: { x: number; y: number; w: number }[] = [];
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] === '#') {
        let w = 1;
        while (row[x + w] === '#') w++;
        out.push({ x, y, w });
        x += w;
      } else x++;
    }
  });
  return out;
}

const CACHE = new Map<IconName, { x: number; y: number; w: number }[]>();

export const PixelIcon = memo(function PixelIcon({
  name,
  size = 16,
  className,
  title,
}: {
  name: IconName;
  size?: number;
  className?: string;
  title?: string;
}) {
  let r = CACHE.get(name);
  if (!r) {
    r = runs(ICONS[name]);
    CACHE.set(name, r);
  }
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 10 10"
      shapeRendering="crispEdges"
      fill="currentColor"
      className={className}
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
    >
      {title ? <title>{title}</title> : null}
      {r.map((p, i) => (
        <rect key={i} x={p.x} y={p.y} width={p.w} height={1} />
      ))}
    </svg>
  );
});
